import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import * as T from '../src/tlog.mjs';
import {BASE, tamper, transparencyFixture, wipeTenant} from './support/transparency-fixture.mjs';

const run = (script, args) => {
  const r = spawnSync(process.execPath, [script, ...args], {encoding: 'utf8', windowsHide: true});
  return {status: r.status, out: r.status === 0 && r.stdout.trim().startsWith('{') ? JSON.parse(r.stdout) : r.stdout, err: r.stderr};
};
const verify = (...args) => run('scripts/verify.mjs', args);

test('verify.mjs keeps positional legacy behaviour and adds opt-in transparency flags', async t => {
  const f = await transparencyFixture(t);
  const keyPath = join(f.root, 'trusted.pem'), file = name => join(f.root, name);
  writeFileSync(keyPath, f.publicKey.export({format: 'pem', type: 'spki'}));
  const legacy = await f.open('off');
  f.write(legacy, 'alpha', 3);
  const legacyExport = await f.call(legacy, '/api/export');
  writeFileSync(file('legacy.json'), JSON.stringify(legacyExport));
  writeFileSync(file('legacy-checkpoint.json'), JSON.stringify(legacyExport.checkpoint));
  await f.close(legacy);
  let r = verify(file('legacy.json'), keyPath);
  assert.equal(r.status, 0, r.err);
  assert.deepEqual(Object.keys(r.out).sort(), ['count', 'disclosedEvents', 'erasedEvents', 'rollbackChecked', 'scope', 'tenant', 'valid']);
  r = verify(file('legacy.json'), keyPath, file('legacy-checkpoint.json'));
  assert.equal(r.out.rollbackChecked, true);
  r = verify(file('legacy.json'), keyPath, '--require-transparency');
  assert.equal(r.status, 1);
  assert.match(r.err, /Transparency evidence missing/);
  r = verify(file('legacy.json'), keyPath, '--min-checkpoint', file('legacy-checkpoint.json'));
  assert.equal(r.status, 0, r.err);
  assert.equal(r.out.rollbackChecked, true);
  assert.equal(r.out.transparency.present, false);

  const s = await f.open('enforce');
  const early = s.store._tlogRow('alpha').note;
  writeFileSync(file('early.note'), early);
  f.write(s, 'alpha', 2);
  await s.transparency.pump();
  writeFileSync(file('export.json'), JSON.stringify(await f.call(s, '/api/export')));
  f.write(s, 'alpha', 1);
  writeFileSync(file('later.note'), s.store._tlogRow('alpha').note);
  r = verify(file('export.json'), keyPath);
  assert.equal(r.status, 0, r.err);
  assert.equal(r.out.transparency.present, true);
  assert.equal(r.out.rollbackChecked, false);
  const witnessed = ['--witness', f.w.vkey, '--quorum', '1', '--origin-base', BASE, '--require-transparency'];
  r = verify(file('export.json'), keyPath, ...witnessed);
  assert.equal(r.status, 0, r.err);
  assert.equal(r.out.rollbackChecked, true);
  assert.equal(r.out.transparency.heads.quorumMet, true);
  r = verify(file('export.json'), keyPath, ...witnessed, '--min-checkpoint', file('early.note'));
  assert.equal(r.out.transparency.minimumCheckpoint.satisfied, true);
  r = verify(file('export.json'), keyPath, '--min-checkpoint', file('later.note'));
  assert.equal(r.status, 1);
  assert.match(r.err, /rollback or truncation/);
  r = verify(file('export.json'), keyPath, '--origin-base', 'other.test/vault');
  assert.equal(r.status, 1);
  assert.match(r.err, /origin/);
  r = verify(file('export.json'), keyPath, '--quorum', 'x');
  assert.equal(r.status, 1);
});

test('transparency.mjs prints witness registration and read-only status', async t => {
  const f = await transparencyFixture(t);
  const keyPath = join(f.root, 'vault.pem'), configPath = join(f.root, 'transparency.json');
  writeFileSync(keyPath, f.privateKey.export({format: 'pem', type: 'pkcs8'}));
  writeFileSync(configPath, JSON.stringify({origin: BASE, mode: 'enforce', witnesses: [{vkey: f.w.vkey, url: f.ws.url}]}));
  let r = run('scripts/transparency.mjs', ['vkeys', '--config', configPath, '--key', keyPath]);
  assert.equal(r.status, 0, r.err);
  assert.equal(r.out.logVkey, T.logVkey(T.headsOrigin(BASE), f.publicKey));
  r = run('scripts/transparency.mjs', ['witnessctl', '--config', configPath, '--key', keyPath, '--db', '/srv/witness.db']);
  assert.equal(r.status, 0, r.err);
  assert.match(r.out, new RegExp(`witnessctl add-log -db /srv/witness.db -origin ${BASE}/heads`));
  assert.ok(r.out.includes(`-key ${T.logVkey(T.headsOrigin(BASE), f.publicKey)}`));
  const s = await f.open('enforce');
  f.write(s, 'alpha', 2);
  await s.transparency.pump();
  await f.close(s);
  r = run('scripts/transparency.mjs', ['status', '--config', configPath, '--key', keyPath, '--data-dir', f.dataDir]);
  assert.equal(r.status, 0, r.err);
  assert.equal(r.out.ok, true);
  assert.equal(r.out.cosignatures[0].configured, true);
  tamper(f.dataDir, db => wipeTenant(db, 'alpha'));
  r = run('scripts/transparency.mjs', ['status', '--config', configPath, '--key', keyPath, '--data-dir', f.dataDir]);
  assert.equal(r.status, 2);
  assert.match(r.out, /tenant removal/);
});
